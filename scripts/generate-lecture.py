#!/usr/bin/env python3
"""
Lecture PDF + PPT generator for AgilePortal Enterprise.
Called by the frontend via a POST request with lecture JSON.
Generates a structured PDF (ReportLab) and PPTX (python-pptx).
"""
import json
import os
import sys
import tempfile
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib.colors import HexColor, white
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_JUSTIFY
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, PageBreak, Table, TableStyle, HRFlowable
)
from pptx import Presentation
from pptx.util import Inches, Pt, Emu

OUTPUT_DIR = "/home/z/my-project/download/lectures"
os.makedirs(OUTPUT_DIR, exist_ok=True)

EMERALD = HexColor("#059669")
SLATE_900 = HexColor("#0F172A")
SLATE_700 = HexColor("#334155")
SLATE_500 = HexColor("#64748B")
SLATE_200 = HexColor("#E2E8F0")
WHITE = HexColor("#FFFFFF")

def generate_pdf(lecture: dict, week_id: int) -> str:
    """Generate a lecture PDF and return the file path."""
    safe_title = "".join(c for c in lecture.get("title", "lecture") if c.isalnum() or c in "-_ ")[:40].strip().replace(" ", "-")
    filename = f"Lecture-W{week_id}-{safe_title}.pdf"
    filepath = os.path.join(OUTPUT_DIR, filename)

    doc = SimpleDocTemplate(
        filepath, pagesize=A4,
        leftMargin=20*mm, rightMargin=20*mm, topMargin=20*mm, bottomMargin=20*mm,
        title=f"AgilePortal Lecture — Week {week_id}: {lecture.get('title', '')}",
        author="AgilePortal Enterprise",
    )

    styles = getSampleStyleSheet()
    style_title = ParagraphStyle("Title", parent=styles["Title"], fontName="Helvetica-Bold", fontSize=22, leading=28, textColor=EMERALD, spaceAfter=4)
    style_sub = ParagraphStyle("Sub", parent=styles["Normal"], fontName="Helvetica", fontSize=12, leading=16, textColor=SLATE_500, spaceAfter=8)
    style_meta = ParagraphStyle("Meta", parent=styles["Normal"], fontName="Helvetica-Bold", fontSize=10, textColor=SLATE_900, spaceAfter=12)
    style_h2 = ParagraphStyle("H2", parent=styles["Heading2"], fontName="Helvetica-Bold", fontSize=14, leading=18, textColor=SLATE_900, spaceBefore=14, spaceAfter=4)
    style_body = ParagraphStyle("Body", parent=styles["Normal"], fontName="Helvetica", fontSize=10, leading=15, textColor=SLATE_700, alignment=TA_JUSTIFY, spaceAfter=6)
    style_bullet = ParagraphStyle("Bullet", parent=style_body, leftIndent=15, bulletIndent=5, spaceAfter=3)
    style_term = ParagraphStyle("Term", parent=style_body, fontName="Helvetica-Bold", textColor=SLATE_900)

    story = []
    # Cover
    story.append(Spacer(1, 40*mm))
    story.append(Paragraph(lecture.get("title", "Lecture"), style_title))
    story.append(Paragraph(lecture.get("subtitle", ""), style_sub))
    story.append(HRFlowable(width="60%", thickness=2, color=EMERALD, spaceAfter=12))
    story.append(Paragraph(f"Week {week_id} · AgilePortal Enterprise", style_meta))
    dur = lecture.get("durationMinutes", 45)
    story.append(Paragraph(f"Duration: {dur} minutes", style_sub))
    story.append(PageBreak())

    # Sections
    story.append(Paragraph("Lecture Content", style_h2))
    story.append(HRFlowable(width="100%", thickness=1, color=SLATE_200, spaceAfter=10))

    for i, section in enumerate(lecture.get("sections", [])):
        story.append(Paragraph(f"{i+1}. {section.get('heading', '')}", style_h2))
        story.append(Paragraph(section.get("content", ""), style_body))
        kps = section.get("keyPoints", [])
        if kps:
            for kp in kps:
                story.append(Paragraph(f"&bull; {kp}", style_bullet))
        story.append(Spacer(1, 6))

    # Summary
    story.append(Spacer(1, 12))
    story.append(Paragraph("Summary", style_h2))
    story.append(HRFlowable(width="100%", thickness=1, color=SLATE_200, spaceAfter=10))
    story.append(Paragraph(lecture.get("summary", ""), style_body))

    # Glossary
    glossary = lecture.get("glossary", [])
    if glossary:
        story.append(Spacer(1, 12))
        story.append(Paragraph("Glossary", style_h2))
        story.append(HRFlowable(width="100%", thickness=1, color=SLATE_200, spaceAfter=10))
        for item in glossary:
            story.append(Paragraph(f"<b>{item.get('term', '')}</b>: {item.get('definition', '')}", style_body))

    # Footer
    story.append(Spacer(1, 20))
    story.append(HRFlowable(width="100%", thickness=0.5, color=SLATE_200, spaceAfter=6))
    footer_style = ParagraphStyle("Footer", parent=style_body, fontSize=8, textColor=SLATE_500, alignment=TA_CENTER)
    story.append(Paragraph(f"© 2026 AgilePortal Enterprise · Generated by AI · Week {week_id} Lecture", footer_style))

    doc.build(story)
    return filepath

def generate_ppt(lecture: dict, week_id: int) -> str:
    """Generate a lecture PPTX and return the file path."""
    safe_title = "".join(c for c in lecture.get("title", "lecture") if c.isalnum() or c in "-_ ")[:40].strip().replace(" ", "-")
    filename = f"Lecture-W{week_id}-{safe_title}.pptx"
    filepath = os.path.join(OUTPUT_DIR, filename)

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    # Title slide
    slide_layout = prs.slide_layouts[6]  # blank
    slide = prs.slides.add_slide(slide_layout)
    # Background
    bg = slide.background
    bg.fill.solid()
    bg.fill.fore_color.rgb = __import__("pptx.dml.color").dml.color.RGBColor(0x0F, 0x17, 0x2A)
    # Title text
    from pptx.util import Pt
    from pptx.dml.color import RGBColor
    txBox = slide.shapes.add_textbox(Inches(1), Inches(2.5), Inches(11.333), Inches(2))
    tf = txBox.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = lecture.get("title", "Lecture")
    p.font.size = Pt(40)
    p.font.bold = True
    p.font.color.rgb = RGBColor(0x05, 0x96, 0x69)
    # Subtitle
    p2 = tf.add_paragraph()
    p2.text = lecture.get("subtitle", "")
    p2.font.size = Pt(18)
    p2.font.color.rgb = RGBColor(0x94, 0xA3, 0xB8)
    # Week + duration
    p3 = tf.add_paragraph()
    p3.text = f"Week {week_id} · {lecture.get('durationMinutes', 45)} min · AgilePortal Enterprise"
    p3.font.size = Pt(12)
    p3.font.color.rgb = RGBColor(0xD9, 0x77, 0x06)
    p3.space_before = Pt(20)

    # Content slides — one per section
    for i, section in enumerate(lecture.get("sections", [])):
        slide = prs.slides.add_slide(prs.slide_layouts[1])  # title + content
        title_shape = slide.shapes.title
        title_shape.text = f"{i+1}. {section.get('heading', '')}"
        title_shape.text_frame.paragraphs[0].font.color.rgb = RGBColor(0x05, 0x96, 0x69)

        body_shape = slide.placeholders[1]
        tf = body_shape.text_frame
        tf.word_wrap = True

        # Content paragraph
        p = tf.paragraphs[0]
        p.text = section.get("content", "")
        p.font.size = Pt(14)
        p.font.color.rgb = RGBColor(0x33, 0x41, 0x55)
        p.space_after = Pt(12)

        # Key points
        for kp in section.get("keyPoints", []):
            p = tf.add_paragraph()
            p.text = f"• {kp}"
            p.font.size = Pt(13)
            p.font.color.rgb = RGBColor(0x47, 0x55, 0x69)
            p.space_after = Pt(6)
            p.level = 1

    # Summary slide
    slide = prs.slides.add_slide(prs.slide_layouts[1])
    slide.shapes.title.text = "Summary"
    slide.shapes.title.text_frame.paragraphs[0].font.color.rgb = RGBColor(0x05, 0x96, 0x69)
    body = slide.placeholders[1]
    body.text_frame.text = lecture.get("summary", "")
    body.text_frame.paragraphs[0].font.size = Pt(14)

    # Glossary slide
    glossary = lecture.get("glossary", [])
    if glossary:
        slide = prs.slides.add_slide(prs.slide_layouts[1])
        slide.shapes.title.text = "Glossary"
        slide.shapes.title.text_frame.paragraphs[0].font.color.rgb = RGBColor(0x05, 0x96, 0x69)
        body = slide.placeholders[1]
        tf = body.text_frame
        tf.word_wrap = True
        for i, item in enumerate(glossary):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.text = f"{item.get('term', '')}: {item.get('definition', '')}"
            p.font.size = Pt(13)
            p.font.color.rgb = RGBColor(0x33, 0x41, 0x55)
            p.space_after = Pt(8)

    prs.save(filepath)
    return filepath

if __name__ == "__main__":
    # Read lecture JSON from stdin
    input_data = json.loads(sys.stdin.read())
    lecture = input_data["lecture"]
    week_id = input_data["weekId"]
    fmt = input_data.get("format", "pdf")

    if fmt == "pdf":
        path = generate_pdf(lecture, week_id)
    else:
        path = generate_ppt(lecture, week_id)

    print(json.dumps({"path": path, "filename": os.path.basename(path)}))
